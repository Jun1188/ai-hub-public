'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
require('../src/core/creation-assistant');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'hub-creation-'));
const store=require('../src/core/creation-studio').createStore(root),doc=require('../src/core/creation-document');
let checks=0;const check=fn=>{fn();checks++;};
const project={pages:[{id:'home',frames:[{component:{type:'wrapper',attributes:{id:'root'},components:[{type:'text',attributes:{id:'first'},content:'First'},{type:'text',attributes:{id:'second'},content:'Second'}]}}]}],styles:[],assets:[]};
try{
 const p=store.create('Design',project);
 const saved=store.save({...p,selection:['first']});
 check(()=>assert.deepEqual(doc.attributes({hidden:true,disabled:false,width:200}),{hidden:true,disabled:false,width:200}));
 check(()=>assert.equal(doc.component({type:'button',tagName:'button',content:'Button'}).type,'button'));
 check(()=>assert.deepEqual(doc.style({'-webkit-tap-highlight-color':'transparent'}),{'-webkit-tap-highlight-color':'transparent'}));
 check(()=>assert.equal(doc.project({...project,styles:[{selectorsAdd:".card > span",style:{color:"red"}}]}).styles.length,1));
 check(()=>assert.equal(saved.revision,1));
 check(()=>assert.equal(store.save({...saved}).revision,1));
 check(()=>assert.throws(()=>store.save({...p,selection:[]}),/다른 편집/));
 check(()=>assert.throws(()=>store.propose({id:p.id,baseRevision:0,summary:'old',operations:[{op:'text',target:'first',value:'x'}]}),/변경/));
 const proposal=store.propose({id:p.id,baseRevision:1,summary:'Change first',operations:[{op:'text',target:'first',value:'Changed'}]});
 check(()=>assert.deepEqual(proposal.scope,['first']));
 check(()=>assert.equal(store.read(p.id).project.pages[0].frames[0].component.components[0].content,'First'));
 check(()=>assert.throws(()=>store.propose({id:p.id,baseRevision:1,summary:'out of scope',operations:[{op:'text',target:'second',value:'x'}]}),/선택/));
 check(()=>assert.throws(()=>doc.proposal({summary:'bad',operations:[{op:'append',target:'first',value:{tagName:'script',content:'bad'}}]})));
 check(()=>assert.throws(()=>doc.proposal({summary:'bad',operations:[{op:'attributes',target:'first',value:{onclick:'bad'}}]})));
 check(()=>assert.throws(()=>doc.style({background:'url(file:///private.png)'})));
 check(()=>assert.throws(()=>doc.style({background:'url(javascript:alert(1))'})));
 check(()=>assert.deepEqual(doc.style({background:'url("https://example.com/image.png")'}),{background:'url("https://example.com/image.png")'}));
 check(()=>assert.throws(()=>doc.component({type:'text',content:'<img src=x onerror=bad>'})));
 check(()=>assert.equal(doc.component({type:'text',content:'Text <b>bold</b><br>next'}).type,'text'));
 const framed=structuredClone(project);framed.pages[0].frames[0].head=[{tag:'script',content:'bad'}];
 check(()=>assert.equal(doc.project(framed).pages[0].frames[0].head,undefined));
 const broken=path.join(root,p.id+'.json');fs.writeFileSync(broken,'broken');
 check(()=>assert.throws(()=>store.read(p.id)));
 check(()=>assert.equal(fs.readFileSync(broken,'utf8'),'broken'));
 const imported=require('../src/core/creation-page-import');
 check(()=>assert.throws(()=>imported.address('http://127.0.0.1/private')));
 check(()=>assert.equal(imported.cssUrls('a{background:url(./pic.png)}','https://example.github.io/path/main.css'),'a{background:url("https://example.github.io/path/pic.png")}'));
 console.log('Creation studio: '+checks+' checks passed; no models, downloads or tools executed');
}finally{fs.rmSync(root,{recursive:true,force:true});}
