'use strict';
const assert = require('assert/strict');
const p = require('../src/core/passthrough-contract');
const probe = require('../src/core/passthrough-probe');
(async () => {
  let now = 1000; const epoch = p.epoch(), receiver = p.receiver('guest', epoch, () => now);
  const hello = p.hello('guest', epoch, 0, now);
  assert.throws(() => receiver.accept({ ...hello, kind: 'heartbeat' }), /handshake/);
  assert.throws(() => receiver.accept({ ...hello, version: 2 }), /version/);
  assert.throws(() => receiver.accept({ ...hello, coordinates: { unit: 'centimeter', up: 'Z' } }), /contract/);
  assert.throws(() => receiver.accept({ ...hello, role: 'host' }), /peer_role/);
  receiver.accept(hello);
  const state = { version: 1, epoch, role: 'guest', seq: 1, timeMs: now, kind: 'state', topic: 'motion', position: [1, 2, 3] };
  receiver.accept(state); assert(receiver.status().connected);
  assert.throws(() => receiver.accept(state), /sequence/);
  assert.throws(() => receiver.accept({ ...state, seq: 2, topic: 'world' }), /ownership/);
  assert.throws(() => receiver.accept({ ...state, seq: 2, position: [NaN, 2, 3] }), /coordinates/);
  assert.throws(() => receiver.accept({ ...state, seq: 2, epoch: p.epoch() }), /epoch/);
  assert.deepEqual(p.toCanonical([100, 200, 300], { unitsPerMeter: 100, axes: ['x', 'z', '-y'] }), [1, 3, -2]);
  assert.throws(() => p.toCanonical([1, 2, 3], { unitsPerMeter: 0, axes: ['x', 'y', 'z'] }), /mapping/);
  now += p.contract.heartbeatTimeoutMs + 1;
  assert.equal(receiver.status().connected, false);
  assert.throws(() => receiver.accept({ ...state, seq: 2, timeMs: now, kind: 'heartbeat' }), /handshake/);
  assert.throws(() => receiver.accept({ ...hello, seq: 2, timeMs: now + 201 }), /time/);
  receiver.accept(p.hello('guest', epoch, 2, now)); assert(receiver.status().connected);
  const restarted = p.receiver('guest', p.epoch(), () => now);
  assert.throws(() => restarted.accept({ ...hello, seq: 3, timeMs: now }), /epoch/);
  assert.throws(() => receiver.accept({ ...state, seq: 3, timeMs: now, padding: 'x'.repeat(4096) }), /size/);
  const result = await probe.run();
  assert.equal(result.ok, true); assert.equal(result.childProcess, true); assert.equal(result.gameInjection, false);
  assert.equal(result.transport, process.platform === 'win32' ? 'windows-native-named-pipe' : 'unix-local-socket');
  assert(result.checks.includes('previous_epoch_rejected')); assert(result.checks.includes('ownership_rejected'));
  console.log('passthrough contract: version/units/ownership/timeout/epoch/coordinates and native local IPC child probe passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
